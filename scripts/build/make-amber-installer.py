#!/usr/bin/env python3
"""Build website/root/attiva-allerte-amber.sh, the script that turns on AMBER Alerts.

The alerts are not part of the Trota OS images: whoever wants them downloads
this single script from the website and runs it as a normal user. It carries
the checker (trota_common/amber.py, the trota-amber-alert command), its systemd
user timer and the default configuration, and installs them in the home folder
(no sudo). docs/amber-alert.md describes it for users.

    python3 scripts/build/make-amber-installer.py          # write the script and its .sha256
    python3 scripts/build/make-amber-installer.py --check  # fail if the committed script is stale
"""
from __future__ import annotations

import argparse
import hashlib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
AMBER = ROOT / "packaging/files/amber"
OUT = ROOT / "website/root/attiva-allerte-amber.sh"
VERSION = "1.0"
EOF_MARK = "TROTA_AMBER_EOF"

HEADER = r'''#!/usr/bin/env bash
# Allerte AMBER per Trota OS __VERSION__ — TestardStudios, GPL-3.0-or-later.
# Generated by scripts/build/make-amber-installer.py: do not edit by hand.
#
# Mostra come notifiche le allerte AMBER (rapimento di minori) quando il fuso
# orario del computer è negli Stati Uniti, dal feed pubblico IPAWS della FEMA.
# La posizione non viene cercata né inviata; fuori dagli Stati Uniti non si
# scarica nulla. Si installa nella cartella personale, senza sudo.
#
#   bash attiva-allerte-amber.sh             attiva le allerte
#   bash attiva-allerte-amber.sh --prova     attiva e mostra una notifica di prova
#   bash attiva-allerte-amber.sh --disattiva le disattiva e rimuove tutto
set -euo pipefail

DATA="${XDG_DATA_HOME:-$HOME/.local/share}/trota-amber-alert"
BIN="$HOME/.local/bin/trota-amber-alert"
CONFIG_DIR="${XDG_CONFIG_HOME:-$HOME/.config}"
UNITS="$CONFIG_DIR/systemd/user"
CONF="$CONFIG_DIR/trota-amber-alert.conf"

die() { echo "Errore: $*" >&2; exit 1; }

[ "$(id -u)" -ne 0 ] || die "esegui lo script come utente normale, senza sudo."
mode="${1:-}"
case "$mode" in
    ""|--prova|--disattiva) ;;
    *) die "opzione sconosciuta '$mode' (usa --prova o --disattiva)." ;;
esac

if [ "$mode" = --disattiva ]; then
    systemctl --user disable --now trota-amber-alert.timer 2>/dev/null || true
    rm -f "$UNITS/trota-amber-alert.timer" "$UNITS/trota-amber-alert.service" "$BIN"
    rm -rf "$DATA"
    systemctl --user daemon-reload 2>/dev/null || true
    echo "Allerte AMBER disattivate. La configurazione $CONF è rimasta: puoi cancellarla."
    exit 0
fi

command -v python3 >/dev/null || die "manca python3."
python3 -c 'import trota_common.osinfo, trota_common.i18n' 2>/dev/null \
    || die "questo script è per Trota OS (manca il modulo trota_common)."
python3 -c 'import gi; gi.require_version("Gio", "2.0"); from gi.repository import Gio' 2>/dev/null \
    || die "manca python3-gi (sudo apt install python3-gi)."

mkdir -p "$DATA" "$(dirname "$BIN")" "$UNITS"
'''

FOOTER = r'''
systemctl --user daemon-reload
systemctl --user enable --now trota-amber-alert.timer >/dev/null

states="$("$BIN" --status)"
echo "Allerte AMBER attivate (controllo ogni 5 minuti)."
if [ "$states" = "-" ]; then
    echo "Il fuso orario non è negli Stati Uniti: per ora non viene scaricato nulla."
else
    echo "Stati seguiti, dal fuso orario: $states"
fi
echo "Configurazione: $CONF — per disattivarle: bash attiva-allerte-amber.sh --disattiva"
if [ "$mode" = --prova ]; then
    "$BIN" --test && echo "Notifica di prova inviata."
fi
'''


def embed(dest: str, text: str, mode: str | None = None) -> str:
    if EOF_MARK in text:
        raise SystemExit(f"{dest}: contains the heredoc delimiter")
    out = f"cat > {dest} <<'{EOF_MARK}'\n{text.rstrip(chr(10))}\n{EOF_MARK}\n"
    if mode:
        out += f"chmod {mode} {dest}\n"
    return out


def build() -> str:
    module = (ROOT / "applications/trota-common/trota_common/amber.py").read_text()
    # Stand-alone copy next to the system trota_common: absolute imports.
    module = module.replace("from .i18n import _", "from trota_common.i18n import _")
    module = module.replace("from .osinfo import parse_os_release", "from trota_common.osinfo import parse_os_release")
    assert "from ." not in module, "amber.py gained a relative import: update make-amber-installer.py"
    conf = (AMBER / "trota-amber-alert.conf").read_text()
    body = (
        embed('"$DATA/trota_amber.py"', module)
        + embed('"$BIN"', (AMBER / "trota-amber-alert").read_text(), "755")
        + embed('"$UNITS/trota-amber-alert.service"', (AMBER / "trota-amber-alert.service").read_text())
        + embed('"$UNITS/trota-amber-alert.timer"', (AMBER / "trota-amber-alert.timer").read_text())
        + '[ -f "$CONF" ] || ' + embed('"$CONF"', conf)
    )
    return HEADER.replace("__VERSION__", VERSION) + "\n" + body + FOOTER


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    text = build()
    digest = f"{hashlib.sha256(text.encode()).hexdigest()}  {OUT.name}\n"
    sha = OUT.with_name(OUT.name + ".sha256")
    if args.check:
        if not OUT.exists() or OUT.read_text() != text or sha.read_text() != digest:
            print(f"{OUT.relative_to(ROOT)} is out of date: run {Path(__file__).relative_to(ROOT)}", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    OUT.chmod(0o755)
    sha.write_text(digest)
    print(OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
