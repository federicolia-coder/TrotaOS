# --- Plymouth spinner frames (not committed: generated at package build) ---
def plymouth_frame(i: int, n: int, size: int = 64, segments: int = 12) -> str:
    cx = cy = size / 2
    r_out, r_in = size / 2 - 2, size / 2 - 12
    head = (i / n) * segments
    shapes = []
    for s in range(segments):
        a0 = (s / segments) * 2 * math.pi - math.pi / 2 + 0.06
        a1 = ((s + 1) / segments) * 2 * math.pi - math.pi / 2 - 0.06
        pts = [
            (cx + r_out * math.cos(a0), cy + r_out * math.sin(a0)),
            (cx + r_out * math.cos(a1), cy + r_out * math.sin(a1)),
            (cx + r_in * math.cos(a1), cy + r_in * math.sin(a1)),
            (cx + r_in * math.cos(a0), cy + r_in * math.sin(a0)),
        ]
        behind = (head - s) % segments
        if behind < 1:
            color, alpha = ORANGE, 1.0
        elif behind < 5:
            color, alpha = ORANGE, max(0.15, 1.0 - behind * 0.22)
        else:
            color, alpha = STEEL, 0.35
        d = "M" + " L".join(f"{x:.2f} {y:.2f}" for x, y in pts) + " Z"
        shapes.append(f'<path d="{d}" fill="{color}" fill-opacity="{alpha:.2f}"/>')
    return svg(size, size, "".join(shapes), title="Trota OS boot")


