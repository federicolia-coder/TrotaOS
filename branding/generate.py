#!/usr/bin/env python3
"""Generate the Trota OS vector artwork from a single geometric definition.

Every committed SVG under branding/ is produced by this script, so the logo,
icons, wallpapers and boot artwork always share the exact same geometry and
palette.  Usage:

    python3 branding/generate.py            # (re)write the committed SVGs
    python3 branding/generate.py --check    # exit 1 if any SVG is out of date
    python3 branding/generate.py --plymouth-frames DIR   # boot spinner frames

No third-party dependency: plain string templates, rendered to PNG by
branding/render.sh (rsvg-convert).  Copyright (C) 2026 TestardStudios.
Artwork license: see branding/LICENSE.md.
"""
from __future__ import annotations

import argparse
import math
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent

# --- Palette (docs/brand.md) -----------------------------------------------
CARBON = "#101214"
GRAPHITE = "#191D21"
STEEL = "#737B84"
FROST = "#E8ECEF"
ORANGE = "#FF6A2A"

# --- Symbol geometry: a stylised trout on a 256x256 grid -------------------
# Built only from straight segments at 0/45-ish degrees: an industrial,
# machined silhouette.  The orange band is the lateral line of a rainbow trout.
BODY = "M60 128 L102 94 L198 94 L238 128 L198 162 L102 162 Z"
TAIL = "M52 128 L16 98 L28 128 L16 158 Z"
FIN = "M124 94 L142 76 L174 76 L164 94 Z"
STRIPE = "M88 123 L214 123 L219 128 L214 133 L88 133 L83 128 Z"
EYE = '<rect x="206" y="112" width="8" height="8"/>'
GILL = "M182 102 L191 128 L182 154"

# --- Wordmark: letters drawn as 18-unit strokes on a 72x100 cell -----------
LETTERS = {
    "T": "M0 9 H72 M36 9 V100",
    "R": "M9 100 V9 H54 L63 18 V41 L54 50 H9 M38 50 L66 100",
    "O": "M18 9 H54 L63 18 V82 L54 91 H18 L9 82 V18 Z",
    "A": "M9 100 V18 L18 9 H54 L63 18 V100 M9 59 H63",
    "S": "M72 9 H18 L9 18 V41 L18 50 H54 L63 59 V82 L54 91 H0",
}
ADVANCE = 90      # 72 cell + 18 spacing
WORD_GAP = 44     # between "TROTA" and "OS"
WORDMARK_W = 4 * ADVANCE + 72 + WORD_GAP + ADVANCE + 72   # 656
WORDMARK_H = 100


def svg(width: float, height: float, body: str, view: str | None = None, title: str = "Trota OS") -> str:
    view = view or f"0 0 {width:g} {height:g}"
    return (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width:g}" height="{height:g}" viewBox="{view}">\n'
        f"<title>{title}</title>\n"
        "<!-- Generated by branding/generate.py - do not edit by hand. (C) 2026 TestardStudios -->\n"
        f"{body}\n</svg>\n"
    )


def symbol(uid: str, fish: str, stripe: str | None, cut_stripe: bool = False) -> str:
    """The trout. Eye and gill are real cut-outs (mask), so the symbol works on
    any background. With stripe=None and cut_stripe the band is cut out too
    (monochrome version)."""
    cuts = [EYE, f'<path d="{GILL}" fill="none" stroke="#000" stroke-width="5" stroke-linejoin="miter"/>']
    if cut_stripe:
        cuts.append(f'<path d="{STRIPE}"/>')
    mask = (
        f'<mask id="cut-{uid}" maskUnits="userSpaceOnUse" x="0" y="0" width="256" height="256">'
        '<rect width="256" height="256" fill="#fff"/>'
        f'<g fill="#000">{"".join(cuts)}</g></mask>'
    )
    parts = [f'<path d="{TAIL}"/>', f'<path d="{BODY}"/>', f'<path d="{FIN}"/>']
    out = f'<defs>{mask}</defs><g mask="url(#cut-{uid})"><g fill="{fish}">{"".join(parts)}</g>'
    if stripe and not cut_stripe:
        out += f'<path d="{STRIPE}" fill="{stripe}"/>'
    return out + "</g>"


def wordmark(uid: str, main: str, accent: str) -> str:
    def letters(text: str, x0: float) -> str:
        return "".join(
            f'<path transform="translate({x0 + i * ADVANCE:g} 0)" d="{LETTERS[c]}"/>' for i, c in enumerate(text)
        )

    os_x = 4 * ADVANCE + 72 + WORD_GAP
    return (
        f'<defs><clipPath id="wm-{uid}"><rect width="{WORDMARK_W}" height="{WORDMARK_H}"/></clipPath></defs>'
        f'<g clip-path="url(#wm-{uid})" fill="none" stroke-width="18" stroke-linejoin="miter" stroke-linecap="butt">'
        f'<g stroke="{main}">{letters("TROTA", 0)}</g>'
        f'<g stroke="{accent}">{letters("OS", os_x)}</g></g>'
    )


def horizontal_logo(uid: str, fish: str, stripe: str | None, main: str, accent: str, cut: bool = False) -> str:
    return svg(
        620, 200,
        f'<g transform="translate(0 8) scale(0.78)">{symbol(uid, fish, stripe, cut)}</g>'
        f'<g transform="translate(210 70) scale(0.6)">{wordmark(uid, main, accent)}</g>',
    )


def stacked_logo(uid: str, fish: str, stripe: str, main: str, accent: str) -> str:
    return svg(
        400, 290,
        f'<g transform="translate(42.5 -50) scale(1.25)">{symbol(uid, fish, stripe)}</g>'
        f'<g transform="translate(36 220) scale(0.5)">{wordmark(uid, main, accent)}</g>',
    )


# --- App icons ---------------------------------------------------------------
