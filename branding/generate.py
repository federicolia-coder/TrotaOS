def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="verify committed SVGs are up to date")
    ap.add_argument("--plymouth-frames", metavar="DIR", type=Path, help="write spinner frame SVGs to DIR")
    ap.add_argument("--frames", type=int, default=36)
    args = ap.parse_args(argv)

    if args.plymouth_frames:
        out = args.plymouth_frames
        out.mkdir(parents=True, exist_ok=True)
        for i in range(args.frames):
            (out / f"throbber-{i + 1:04d}.svg").write_text(plymouth_frame(i, args.frames))
        for name, content in plymouth_static().items():
            (out / name).write_text(content)
        return 0

    stale = []
    for rel, content in committed_assets().items():
        path = HERE / rel
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(rel)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if stale:
        print("out of date (run branding/generate.py):", *stale, sep="\n  ", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
