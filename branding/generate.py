# --- Wallpapers --------------------------------------------------------------
def grid(uid: str, color: str, minor: float, major: float) -> str:
    return (
        f'<pattern id="minor-{uid}" width="80" height="80" patternUnits="userSpaceOnUse">'
        f'<path d="M80 0 H0 V80" fill="none" stroke="{color}" stroke-opacity="{minor}" stroke-width="2"/></pattern>'
        f'<pattern id="major-{uid}" width="400" height="400" patternUnits="userSpaceOnUse">'
        f'<path d="M400 0 H0 V400" fill="none" stroke="{color}" stroke-opacity="{major}" stroke-width="2"/></pattern>'
    )


def ruler(color: str, opacity: float, height: int) -> str:
    ticks = []
    for y in range(80, height - 40, 40):
        length = 36 if y % 200 == 0 else 16
        ticks.append(f"M0 {y} H{length}")
    return f'<path d="{" ".join(ticks)}" stroke="{color}" stroke-opacity="{opacity}" stroke-width="3"/>'


def fish_outline(transform: str, line: str, line_width: float, stripe: str, eye: str) -> str:
    return (
        f'<g transform="{transform}">'
        f'<g fill="none" stroke="{line}" stroke-width="{line_width:g}" stroke-linejoin="miter">'
        f'<path d="{TAIL}"/><path d="{BODY}"/><path d="{FIN}"/><path d="{GILL}"/></g>'
        f'<path d="{STRIPE}" fill="{stripe}"/>'
        f'<g fill="{eye}">{EYE}</g></g>'
    )


def wallpaper(uid: str, light: bool) -> str:
    w, h = 3840, 2160
    if light:
        bg0, bg1, line, grid_c, minor, major, mark = "#EEF1F3", "#D3D8DD", STEEL, CARBON, 0.05, 0.08, CARBON
    else:
        bg0, bg1, line, grid_c, minor, major, mark = "#1A1E22", "#0C0E10", STEEL, FROST, 0.025, 0.05, FROST
    scale = 7
    tx, ty = 1640, 300
    x_left, x_right = tx + 20 * scale, tx + 232 * scale
    dim_y = ty + 174 * scale + 150
    dims = (
        f'<g stroke="{line}" stroke-opacity="0.55" stroke-width="3" fill="none">'
        f"<path d=\"M{x_left} {dim_y} H{x_right} M{x_left} {dim_y - 30} V{dim_y + 30} M{x_right} {dim_y - 30} V{dim_y + 30}\"/>"
        f"<path d=\"M{x_left + 40} {dim_y - 16} L{x_left} {dim_y} L{x_left + 40} {dim_y + 16} "
        f"M{x_right - 40} {dim_y - 16} L{x_right} {dim_y} L{x_right - 40} {dim_y + 16}\"/></g>"
        f'<path d="M{(x_left + x_right) // 2 - 60} {dim_y} H{(x_left + x_right) // 2 + 60}" stroke="{ORANGE}" stroke-width="6"/>'
    )
    crop = (
        f'<path d="M120 80 H80 V120 M{w - 120} 80 H{w - 80} V120 M120 {h - 80} H80 V{h - 120} '
        f'M{w - 120} {h - 80} H{w - 80} V{h - 120}" fill="none" stroke="{mark}" stroke-opacity="0.25" stroke-width="4"/>'
    )
    body = (
        f'<defs><linearGradient id="bg-{uid}" x1="0" y1="0" x2="1" y2="1">'
        f'<stop offset="0" stop-color="{bg0}"/><stop offset="1" stop-color="{bg1}"/></linearGradient>'
        f'<radialGradient id="glow-{uid}" cx="{tx + 150 * scale}" cy="{ty + 128 * scale}" r="1400" gradientUnits="userSpaceOnUse">'
        f'<stop offset="0" stop-color="{ORANGE}" stop-opacity="{0.10 if not light else 0.08}"/>'
        f'<stop offset="1" stop-color="{ORANGE}" stop-opacity="0"/></radialGradient>'
        f"{grid(uid, grid_c, minor, major)}</defs>"
        f'<rect width="{w}" height="{h}" fill="url(#bg-{uid})"/>'
        f'<rect width="{w}" height="{h}" fill="url(#minor-{uid})"/>'
        f'<rect width="{w}" height="{h}" fill="url(#major-{uid})"/>'
        f'<rect width="{w}" height="{h}" fill="url(#glow-{uid})"/>'
        f'<g transform="translate({w - 40} 0) scale(-1 1)">{ruler(mark, 0.18, h)}</g>'
        f"{crop}"
        f"{fish_outline(f'translate({tx} {ty}) scale({scale})', line, 0.55, ORANGE, line)}"
        f"{dims}"
        f'<g transform="translate(560 {h - 200}) scale(0.5)" opacity="{0.35 if not light else 0.45}">'
        f"{wordmark(uid, mark, ORANGE)}</g>"
    )
    return svg(w, h, body, title="Trota OS wallpaper")


def wallpaper_ingot() -> str:
    """Dark wallpaper with a solid, centred silhouette."""
    w, h, uid = 3840, 2160, "ingot"
    scale = 9
    tx = w / 2 - 126 * scale
    ty = h / 2 - 118 * scale
    body = (
        f'<defs><linearGradient id="bg-{uid}" x1="0" y1="0" x2="0" y2="1">'
        f'<stop offset="0" stop-color="{GRAPHITE}"/><stop offset="1" stop-color="{CARBON}"/></linearGradient>'
        f'<linearGradient id="fish-{uid}" x1="0" y1="0" x2="0" y2="1">'
        f'<stop offset="0" stop-color="#262B31"/><stop offset="1" stop-color="#16191C"/></linearGradient>'
        f"{grid(uid, FROST, 0.02, 0.035)}</defs>"
        f'<rect width="{w}" height="{h}" fill="url(#bg-{uid})"/>'
        f'<rect width="{w}" height="{h}" fill="url(#minor-{uid})"/>'
        f'<rect width="{w}" height="{h}" fill="url(#major-{uid})"/>'
        f'<g transform="translate({tx:g} {ty:g}) scale({scale})">'
        f'{symbol(uid, f"url(#fish-{uid})", ORANGE)}'
        f'<path d="{BODY}" fill="none" stroke="#2F353C" stroke-width="0.6"/></g>'
    )
    return svg(w, h, body, title="Trota OS wallpaper")


